#!/usr/bin/env bash
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FASTQ_MIXER="${FASTQ_MIXER:-$SCRIPT_DIR/rrmg_mix_paired_fastq.py}"

usage() {
  cat <<'USAGE'
Usage:
  rrmg_step5_afum_target_reads_genome_cov.sh plan.tsv ROW_INDEX \
    -w /path/to/project \
    --target-genome ref/Afum_Af293.fasta

Purpose:
  Map simulated target-only Afum reads generated by Step 2 back to the Afum
  target genome and calculate genome-wide mapping / coverage summary.

Inputs expected:
  temp/rrmg_permutation/<run_id>/reads/*target_1.fastq.gz
  temp/rrmg_permutation/<run_id>/reads/*target_2.fastq.gz

Outputs:
  temp/rrmg_permutation/<run_id>/target_readmap/
    afum_target_reads_to_genome.bam
    afum_target_reads_to_genome.bam.bai
    afum_target_reads_to_genome.flagstat.txt
    afum_target_reads_to_genome.idxstats.tsv
    afum_target_reads_to_genome.coverage.tsv
    afum_target_reads_to_genome.summary.tsv
    afum_target_reads_to_genome.bins.tsv        only if --make-bins is used

Options:
  --target-genome FILE      Afum genome FASTA. If omitted, use target_fasta in design/plan.
  --root DIR                permutation root. Default: temp/rrmg_permutation
  --make-bins               generate binned mean-depth table using samtools bedcov
  --bin-size N              bin size for --make-bins. Default: 10000
  --force                   overwrite existing outputs
  --remove-bam              remove BAM and BAI after summary to save space
  --readlen N               fallback read length if not found in plan/design. Default: 150

Environment:
  THREADS                   minimap2/samtools threads. Default: 8
  MINIMAP2_BIN              default: minimap2
  SAMTOOLS_BIN              default: samtools
USAGE
}

PLAN="${1:-}"
ROW_INDEX="${2:-${PBS_ARRAY_INDEX:-}}"

if [[ -z "$PLAN" || -z "$ROW_INDEX" ]]; then
  usage
  exit 1
fi
shift 2 || true

WD=""
TARGET_GENOME=""
ROOT="temp/rrmg_permutation"
MAKE_BINS=0
BIN_SIZE=10000
FORCE=0
KEEP_BAM=1
READLEN_DEFAULT=150

while [[ $# -gt 0 ]]; do
  case "$1" in
    -w) WD="$2"; shift 2;;
    --target-genome) TARGET_GENOME="$2"; shift 2;;
    --root) ROOT="$2"; shift 2;;
    --make-bins) MAKE_BINS=1; shift 1;;
    --bin-size) BIN_SIZE="$2"; shift 2;;
    --force) FORCE=1; shift 1;;
    --keep-bam) KEEP_BAM=1; shift 1;;
    --remove-bam) KEEP_BAM=0; shift 1;;
    --readlen) READLEN_DEFAULT="$2"; shift 2;;
    -h|--help) usage; exit 0;;
    *) echo "[ERROR] Unknown arg: $1" >&2; usage; exit 1;;
  esac
done

: "${WD:?Missing -w}"

THREADS="${THREADS:-8}"
MINIMAP2_BIN="${MINIMAP2_BIN:-minimap2}"
SAMTOOLS_BIN="${SAMTOOLS_BIN:-samtools}"

WD="$(mkdir -p "$WD" && cd "$WD" && pwd)"
cd "$WD"

[[ -s "$PLAN" ]] || { echo "[ERROR] Missing plan: $PLAN" >&2; exit 1; }
[[ -s "$FASTQ_MIXER" ]] || { echo "[ERROR] FASTQ audit utility not found: $FASTQ_MIXER" >&2; exit 1; }
command -v "$MINIMAP2_BIN" >/dev/null 2>&1 || { echo "[ERROR] minimap2 not found: $MINIMAP2_BIN" >&2; exit 1; }
command -v "$SAMTOOLS_BIN" >/dev/null 2>&1 || { echo "[ERROR] samtools not found: $SAMTOOLS_BIN" >&2; exit 1; }

marker_matches() {
  local marker="$1" expected="$2"
  [[ -s "$marker" && "$(tr -d '\r\n' < "$marker")" == "$expected" ]]
}

write_marker() {
  local marker="$1" value="$2" temporary="${1}.tmp.$$"
  printf '%s\n' "$value" > "$temporary"
  mv -f -- "$temporary" "$marker"
}

mkdir -p "${WD}/temp"
ROW_ENV="$(mktemp "${WD}/temp/rrmg_afum_genomecov_row_env.XXXXXX")"

python3 - "$PLAN" "$ROW_INDEX" "$WD" "$ROOT" "$TARGET_GENOME" "$READLEN_DEFAULT" > "$ROW_ENV" <<'ROWPY'
import csv
import re
import shlex
import sys
from pathlib import Path

plan = Path(sys.argv[1])
row_index = int(float(sys.argv[2]))
wd = Path(sys.argv[3])
root = sys.argv[4]
target_genome_arg = sys.argv[5]
readlen_default = int(float(sys.argv[6]))

def safe(s):
    s = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(s).strip())
    return s.strip("_") or "NA"

def q(v):
    return shlex.quote(str(v))

def resolve(p):
    if not p:
        return ""
    p = Path(p)
    return str(p if p.is_absolute() else wd / p)

def read_kv(path):
    d = {}
    p = Path(path)
    if not p.exists():
        return d
    with p.open(errors="ignore") as fh:
        header = fh.readline().rstrip("\n").split("\t")
        if len(header) >= 2 and header[0] == "key":
            for line in fh:
                parts = line.rstrip("\n").split("\t", 1)
                if len(parts) == 2:
                    d[parts[0]] = parts[1]
    return d

with plan.open(newline="", errors="ignore") as fh:
    rows = list(csv.DictReader(fh, delimiter="\t"))

chosen = None
for row in rows:
    idx = row.get("run_index", "")
    if idx and int(float(idx)) == row_index:
        chosen = row
        break
if chosen is None and 1 <= row_index <= len(rows):
    chosen = rows[row_index - 1]
if chosen is None:
    raise SystemExit("[ERROR] plan row not found: {}".format(row_index))

sample = chosen.get("sample", "")
seed = chosen.get("seed", row_index)
run_id = chosen.get("run_id", "")
if not run_id:
    if sample:
        run_id = "{}__Seed{}".format(sample, seed)
    else:
        run_id = "AirMG_Afum__ta{}__pairs{}__Seed{}".format(chosen.get("target_abundance", ""), chosen.get("total_pairs", ""), seed)

run_dir = Path(resolve(root)) / safe(run_id)
if not run_dir.exists():
    candidates = list(Path(resolve(root)).glob("*Seed{}*".format(seed)))
    ta = chosen.get("target_abundance", "")
    tp = chosen.get("total_pairs", "")
    candidates = [x for x in candidates if ("ta{}".format(ta) in x.name and "pairs{}".format(tp) in x.name)]
    if candidates:
        run_dir = candidates[0]
if not run_dir.exists():
    raise SystemExit("[ERROR] run_dir not found for run_id={}: {}".format(run_id, run_dir))

design = read_kv(run_dir / "design" / "merge_design.tsv")
target_gid = design.get("target_genome_id", "") or chosen.get("target_genome_id", "") or "Afum"
target_fasta = target_genome_arg or design.get("target_fasta", "") or chosen.get("target_fasta", "")
target_fasta = resolve(target_fasta)
if not target_fasta or not Path(target_fasta).exists():
    raise SystemExit("[ERROR] target genome FASTA not found: {}".format(target_fasta))

readlen = int(float(design.get("readlen", "") or chosen.get("readlen", "") or readlen_default))
target_pairs_design = design.get("target_pairs", "")
target_cov_design = design.get("target_cov", "")
target_abundance = design.get("target_abundance", "") or chosen.get("target_abundance", "")
total_pairs = design.get("total_pairs", "") or chosen.get("total_pairs", "")

reads_dir = run_dir / "reads"
r1_candidates = sorted(reads_dir.glob("*target_1.fastq.gz"))
if target_gid:
    preferred = sorted(reads_dir.glob("{}*.target_1.fastq.gz".format(safe(target_gid))))
    if preferred:
        r1_candidates = preferred
if not r1_candidates:
    raise SystemExit("[ERROR] target-only R1 not found in {}. Did you rerun Step2 with --keep-target-reads?".format(reads_dir))
r1 = r1_candidates[0]
r2 = Path(str(r1).replace("_1.fastq.gz", "_2.fastq.gz"))
if not r2.exists():
    raise SystemExit("[ERROR] target-only R2 not found for {}".format(r1))

out_dir = run_dir / "target_readmap"
out_dir.mkdir(parents=True, exist_ok=True)

vals = {
    "ROW_INDEX": row_index,
    "RUN_ID": run_dir.name,
    "RUN_DIR": str(run_dir),
    "SAMPLE": sample,
    "SEED": seed,
    "TARGET_GENOME_ID": target_gid,
    "TARGET_GENOME_FASTA": target_fasta,
    "TARGET_R1": str(r1),
    "TARGET_R2": str(r2),
    "READLEN": readlen,
    "TARGET_PAIRS_DESIGN": target_pairs_design,
    "TARGET_COV_DESIGN": target_cov_design,
    "TARGET_ABUNDANCE": target_abundance,
    "TOTAL_PAIRS": total_pairs,
    "OUT_DIR": str(out_dir),
}
for k, v in vals.items():
    print("{}={}".format(k, q(v)))
ROWPY

source "$ROW_ENV"
rm -f "$ROW_ENV"

mkdir -p "$OUT_DIR"
PREFIX="${OUT_DIR}/afum_target_reads_to_genome"
BAM="${PREFIX}.bam"
COV="${PREFIX}.coverage.tsv"
IDX="${PREFIX}.idxstats.tsv"
FLAG="${PREFIX}.flagstat.txt"
SUMMARY="${PREFIX}.summary.tsv"
OUTPUT_PROVENANCE="${PREFIX}.mix_generation.txt"
BINS="${PREFIX}.bins.tsv"
WINDOWS="${PREFIX}.windows.${BIN_SIZE}.bed"

echo "[INFO] ROW_INDEX           = $ROW_INDEX"
echo "[INFO] RUN_ID              = $RUN_ID"
echo "[INFO] TARGET_GENOME_FASTA = $TARGET_GENOME_FASTA"
echo "[INFO] TARGET_R1           = $TARGET_R1"
echo "[INFO] TARGET_R2           = $TARGET_R2"
echo "[INFO] MAKE_BINS           = $MAKE_BINS"

[[ -n "$TOTAL_PAIRS" ]] || { echo "[ERROR] Plan/design has no total_pairs" >&2; exit 1; }
[[ -n "$TARGET_PAIRS_DESIGN" ]] || { echo "[ERROR] merge_design.tsv has no target_pairs" >&2; exit 1; }
MIX_AUDIT="${RUN_DIR}/design/read_mix_audit.tsv"
TARGET_PAIRS_EXPECTED="$(python3 - "$TARGET_PAIRS_DESIGN" <<'PY'
import sys
value = float(sys.argv[1])
if value < 0 or not value.is_integer():
    raise SystemExit('[ERROR] Invalid target_pairs in merge design: ' + sys.argv[1])
print(int(value))
PY
)"
TOTAL_PAIRS_EXPECTED="$(python3 - "$TOTAL_PAIRS" <<'PY'
import sys
value = float(sys.argv[1])
if value <= 0 or not value.is_integer():
    raise SystemExit('[ERROR] Invalid total_pairs in plan/design: ' + sys.argv[1])
print(int(value))
PY
)"
BACKGROUND_PAIRS_EXPECTED=$((TOTAL_PAIRS_EXPECTED - TARGET_PAIRS_EXPECTED))
python3 "$FASTQ_MIXER" validate-mix --audit "$MIX_AUDIT" --expected-pairs "$TOTAL_PAIRS_EXPECTED" \
  --expected-background-pairs "$BACKGROUND_PAIRS_EXPECTED" --expected-target-pairs "$TARGET_PAIRS_EXPECTED"
MIX_GENERATION="$(awk -F '\t' '$1=="mix_generation_id"{print $2}' "$MIX_AUDIT")"
TARGET_PAIRS_OBSERVED="$(python3 "$FASTQ_MIXER" count --r1 "$TARGET_R1" --r2 "$TARGET_R2")"
if [[ "$TARGET_PAIRS_OBSERVED" != "$TARGET_PAIRS_EXPECTED" ]]; then
  echo "[ERROR] Target-only FASTQ pair count differs from design: expected=$TARGET_PAIRS_EXPECTED observed=$TARGET_PAIRS_OBSERVED" >&2
  echo "        Rerun corrected Step 2 with --keep-target-reads; this Step 5 result would be quantitatively invalid." >&2
  exit 1
fi
echo "[TARGET-PAIR-AUDIT] expected=$TARGET_PAIRS_EXPECTED observed=$TARGET_PAIRS_OBSERVED"

if [[ "$FORCE" -eq 0 && -s "$SUMMARY" ]]; then
  if marker_matches "$OUTPUT_PROVENANCE" "$MIX_GENERATION"; then
    if [[ "$MAKE_BINS" -eq 0 || -s "$BINS" ]]; then
      echo "[SKIP] existing audited summary: $SUMMARY"
      exit 0
    fi
    echo "[STALE] Current Step 5 summary has no requested bins; regenerating it."
  else
    echo "[STALE] Existing Step 5 summary does not match the current read-mix generation; regenerating it."
  fi
fi

rm -f "$BAM" "${BAM}.bai" "$COV" "$IDX" "$FLAG" "$SUMMARY" "$BINS" "$WINDOWS" "$OUTPUT_PROVENANCE"

"$MINIMAP2_BIN" -t "$THREADS" -ax sr --secondary=no "$TARGET_GENOME_FASTA" "$TARGET_R1" "$TARGET_R2" \
  2> "${PREFIX}.minimap2.log" \
| "$SAMTOOLS_BIN" view -@ "$THREADS" -b - \
| "$SAMTOOLS_BIN" sort -@ "$THREADS" -o "$BAM" -

"$SAMTOOLS_BIN" index "$BAM"
"$SAMTOOLS_BIN" flagstat "$BAM" > "$FLAG"
"$SAMTOOLS_BIN" idxstats "$BAM" > "$IDX"
"$SAMTOOLS_BIN" coverage "$BAM" > "$COV"

if [[ "$MAKE_BINS" -eq 1 ]]; then
  "$SAMTOOLS_BIN" faidx "$TARGET_GENOME_FASTA"
  python3 - "$TARGET_GENOME_FASTA.fai" "$BIN_SIZE" "$WINDOWS" <<'BINPY'
import sys
from pathlib import Path
fai = Path(sys.argv[1]); bin_size = int(sys.argv[2]); out = Path(sys.argv[3])
with fai.open() as fh, out.open('w') as oh:
    for line in fh:
        if not line.strip():
            continue
        chrom, length = line.split('\t')[:2]
        length = int(length)
        for start in range(0, length, bin_size):
            end = min(start + bin_size, length)
            oh.write(f"{chrom}\t{start}\t{end}\n")
BINPY
  "$SAMTOOLS_BIN" bedcov "$WINDOWS" "$BAM" \
  | awk 'BEGIN{OFS="\t"; print "contig","start0","end","bin_len","depth_sum","mean_depth"} {len=$3-$2; print $1,$2,$3,len,$4,$4/len}' \
  > "$BINS"
fi

python3 - "$SUMMARY" "$COV" "$IDX" "$TARGET_GENOME_FASTA" "$TARGET_R1" "$TARGET_R2" \
  "$RUN_ID" "$ROW_INDEX" "$SAMPLE" "$SEED" "$TARGET_GENOME_ID" "$READLEN" \
  "$TARGET_PAIRS_DESIGN" "$TARGET_COV_DESIGN" "$TARGET_ABUNDANCE" "$TOTAL_PAIRS" \
  "$BAM" "$COV" "$IDX" "$FLAG" "$BINS" <<'SUMMYPY'
import csv, gzip, sys
from pathlib import Path
(summary_file, cov_file, idx_file, target_fasta, r1, r2, run_id, row_index, sample, seed, target_gid, readlen, target_pairs_design, target_cov_design, target_abundance, total_pairs, bam, cov_path, idx_path, flag_path, bins_path) = sys.argv[1:]
readlen = int(float(readlen))
def open_text(path): return gzip.open(path, 'rt') if str(path).endswith('.gz') else open(path, 'r', errors='ignore')
def fasta_len(path):
    n=0
    with open_text(path) as fh:
        for line in fh:
            if not line.startswith('>'): n += len(line.strip())
    return n
def count_fastq_records(path):
    n=0
    with open_text(path) as fh:
        for _ in fh: n += 1
    return n//4
def fnum(x):
    try:
        return None if x is None or str(x)=='' else float(x)
    except Exception: return None

genome_bp = fasta_len(target_fasta)
fastq_pairs = count_fastq_records(r1)
coverage_rows=[]
with open(cov_file, newline='', errors='ignore') as fh:
    reader = csv.DictReader((line.lstrip('#') for line in fh), delimiter='\t')
    for row in reader: coverage_rows.append(row)
total_covbases=0; weighted_depth_sum=0.0; weighted_cov_pct_sum=0.0; total_numreads=0
for r in coverage_rows:
    start=int(float(r.get('startpos',1))); end=int(float(r.get('endpos',0))); length=max(0,end-start+1)
    covbases=int(float(r.get('covbases',0))); meandepth=float(r.get('meandepth',0)); covpct=float(r.get('coverage',0)); numreads=int(float(r.get('numreads',0)))
    total_covbases += covbases; weighted_depth_sum += meandepth*length; weighted_cov_pct_sum += covpct*length; total_numreads += numreads
observed_mean_depth = weighted_depth_sum / genome_bp if genome_bp else 0
observed_breadth_pct = total_covbases / genome_bp * 100 if genome_bp else 0
coverage_pct_weighted = weighted_cov_pct_sum / genome_bp if genome_bp else 0
target_pairs_design_num = fnum(target_pairs_design)
expected_cov_from_fastq = fastq_pairs * readlen * 2.0 / genome_bp if genome_bp else 0
expected_cov_from_design_pairs = target_pairs_design_num*readlen*2.0/genome_bp if target_pairs_design_num is not None and genome_bp else ''
idx_mapped=0; idx_unmapped=0
with open(idx_file, errors='ignore') as fh:
    for line in fh:
        parts=line.rstrip('\n').split('\t')
        if len(parts)>=4 and parts[0] != '*':
            idx_mapped += int(parts[2]); idx_unmapped += int(parts[3])
fields=['RunID','RowIndex','Sample','Seed','TargetGenomeID','TargetAbundanceDesign','TotalPairs','TargetGenomeFA','TargetGenomeBp','ReadLen','TargetPairsDesign','TargetPairsFastq','TargetCovDesign','TargetCovFromDesignPairs','TargetCovFromFastq','ObservedMeanDepth','ObservedBreadthPct','ObservedCoveredBp','SamtoolsCoverageWeightedPct','SamtoolsCoverageNumReads','IdxstatsMappedAlignments','IdxstatsUnmappedAlignments','R1','R2','BAM','CoverageTSV','IdxstatsTSV','FlagstatTXT','BinsTSV']
row={'RunID':run_id,'RowIndex':row_index,'Sample':sample,'Seed':seed,'TargetGenomeID':target_gid,'TargetAbundanceDesign':target_abundance,'TotalPairs':total_pairs,'TargetGenomeFA':target_fasta,'TargetGenomeBp':genome_bp,'ReadLen':readlen,'TargetPairsDesign':target_pairs_design,'TargetPairsFastq':fastq_pairs,'TargetCovDesign':target_cov_design,'TargetCovFromDesignPairs':expected_cov_from_design_pairs,'TargetCovFromFastq':f'{expected_cov_from_fastq:.10f}','ObservedMeanDepth':f'{observed_mean_depth:.10f}','ObservedBreadthPct':f'{observed_breadth_pct:.6f}','ObservedCoveredBp':total_covbases,'SamtoolsCoverageWeightedPct':f'{coverage_pct_weighted:.6f}','SamtoolsCoverageNumReads':total_numreads,'IdxstatsMappedAlignments':idx_mapped,'IdxstatsUnmappedAlignments':idx_unmapped,'R1':r1,'R2':r2,'BAM':bam,'CoverageTSV':cov_path,'IdxstatsTSV':idx_path,'FlagstatTXT':flag_path,'BinsTSV':bins_path if Path(bins_path).exists() else ''}
with open(summary_file,'w',newline='') as fh:
    w=csv.DictWriter(fh,fieldnames=fields,delimiter='\t',lineterminator='\n'); w.writeheader(); w.writerow(row)
SUMMYPY

if [[ "$KEEP_BAM" -eq 0 ]]; then
  rm -f "$BAM" "${BAM}.bai"
fi
[[ -s "$SUMMARY" ]] || { echo "[ERROR] summary not created: $SUMMARY" >&2; exit 1; }
write_marker "$OUTPUT_PROVENANCE" "$MIX_GENERATION"
echo "[DONE] $SUMMARY"
